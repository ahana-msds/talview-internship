// number type
let age: number = 21;

// string type
let name1: string = "Ahana";

// boolean type
let isStudent: boolean = true;

// array of numbers
let marks: number[] = [80, 85, 90];

// tuple (fixed order + types)
let user: [string, number] = ["Ahana", 21];

// object with type
let profile: { name: string; age: number } = {
    name: "Ahana",
    age: 21
};

console.log(age, name1, isStudent, marks, user, profile);
